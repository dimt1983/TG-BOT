def init_db():
    con = sqlite3.connect(DB_PATH)
    cur = con.cursor()
    cur.executescript("""
        CREATE TABLE IF NOT EXISTS categories (
            id        INTEGER PRIMARY KEY AUTOINCREMENT,
            name      TEXT NOT NULL,
            parent_id INTEGER REFERENCES categories(id)
        );

        CREATE TABLE IF NOT EXISTS products (
            id           INTEGER PRIMARY KEY AUTOINCREMENT,
            name         TEXT    NOT NULL,
            description  TEXT,
            recipe_e     TEXT,
            recipe_f     TEXT,
            roast_type   TEXT,
            process      TEXT,
            weight_g     INTEGER NOT NULL DEFAULT 1000,
            price        REAL    NOT NULL DEFAULT 0,
            stock        INTEGER NOT NULL DEFAULT 0,
            category_id  INTEGER REFERENCES categories(id),
            photo_url    TEXT
        );

        CREATE TABLE IF NOT EXISTS users (
            user_id        INTEGER PRIMARY KEY,
            tg_name        TEXT,
            user_type      TEXT DEFAULT 'individual',
            name           TEXT,
            phone          TEXT,
            city           TEXT,
            address        TEXT,
            company_name   TEXT,
            inn            TEXT,
            legal_address  TEXT,
            actual_address TEXT,
            email          TEXT,
            created_at     DATETIME DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS cart (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id    INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            quantity   INTEGER NOT NULL DEFAULT 1,
            FOREIGN KEY (product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS orders (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id    INTEGER NOT NULL,
            name       TEXT,
            phone      TEXT,
            address    TEXT,
            total      REAL,
            discount   REAL DEFAULT 0,
            status     TEXT DEFAULT 'new',
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS order_items (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            order_id   INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            quantity   INTEGER NOT NULL,
            price      REAL    NOT NULL,
            FOREIGN KEY (order_id)   REFERENCES orders(id),
            FOREIGN KEY (product_id) REFERENCES products(id)
        );

        CREATE TABLE IF NOT EXISTS wishlist (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id    INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            UNIQUE(user_id, product_id)
        );

        CREATE TABLE IF NOT EXISTS notify_when_available (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id    INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            UNIQUE(user_id, product_id)
        );

        CREATE TABLE IF NOT EXISTS promo_codes (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            code       TEXT    NOT NULL UNIQUE,
            discount   REAL    NOT NULL,
            uses_left  INTEGER NOT NULL DEFAULT 1,
            user_id    INTEGER,
            is_active  INTEGER NOT NULL DEFAULT 1,
            created_at TEXT    DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS admin_log (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            admin_id   INTEGER NOT NULL,
            action     TEXT    NOT NULL,
            created_at TEXT    NOT NULL
        );
    """)

    # Миграция users
    existing_cols = [row[1] for row in cur.execute("PRAGMA table_info(users)").fetchall()]
    for col, typ in [
        ("user_type", "TEXT DEFAULT 'individual'"),
        ("company_name", "TEXT"), ("inn", "TEXT"),
        ("legal_address", "TEXT"), ("actual_address", "TEXT"), ("email", "TEXT"),
    ]:
        if col not in existing_cols:
            cur.execute(f"ALTER TABLE users ADD COLUMN {col} {typ}")

    # Миграция products
    prod_cols = [row[1] for row in cur.execute("PRAGMA table_info(products)").fetchall()]
    for col, typ in [
        ("description", "TEXT"), ("recipe_e", "TEXT"), ("recipe_f", "TEXT"),
        ("roast_type", "TEXT"), ("process", "TEXT"), ("weight_g", "INTEGER DEFAULT 1000"),
        ("photo_url", "TEXT"),
        ("price_10kg", "REAL DEFAULT 0"),  # цена при заказе от 10 кг (-10%)
        ("price_25kg", "REAL DEFAULT 0"),  # цена при заказе от 25 кг (-20%)
    ]:
        if col not in prod_cols:
            cur.execute(f"ALTER TABLE products ADD COLUMN {col} {typ}")

    # Наполняем каталог если пустой
    cur.execute("SELECT COUNT(*) FROM categories")
    if cur.fetchone()[0] == 0:
        _seed_catalog(cur)

    con.commit()
    con.close()


