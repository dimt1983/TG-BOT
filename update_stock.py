def update_stock():
    con = sqlite3.connect("shop.db")
    con.row_factory = sqlite3.Row
    cur = con.cursor()

    updated, not_found = [], []

    for label, stock, pattern in STOCK_MAP:
        rows = cur.execute(
            "SELECT id, name FROM products WHERE name LIKE ?", (pattern,)
        ).fetchall()
        if rows:
            for row in rows:
                cur.execute("UPDATE products SET stock = ? WHERE id = ?", (stock, row["id"]))
                updated.append(f"  ✅ [{stock:>4}]  {row['name']}")
        else:
            not_found.append(f"  ❌ Не найдено: «{label}»  (паттерн: {pattern})")

    con.commit()
    con.close()

    print(f"\n{'='*65}")
    print(f"ОБНОВЛЕНО ({len(updated)} позиций):")
    print("\n".join(updated))
    if not_found:
        print(f"\nНЕ НАЙДЕНО ({len(not_found)}):")
        print("\n".join(not_found))
    print(f"{'='*65}\n")
    print("✅ Готово! Загрузи обновлённый shop.db на Render.")


if __name__ == "__main__":
    update_stock()
